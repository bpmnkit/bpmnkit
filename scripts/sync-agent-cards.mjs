#!/usr/bin/env node
// Copies the agent cards (apps/cli/agent-cards/<kind>.md, the single source) into
// the landing docs, which feed @bpmnkit/docspack, and into the Claude plugin's
// skills. `--check` writes nothing and exits 1 when a copy is stale; the CLI's
// agent-card test runs it so a card edit cannot ship without its copies.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("..", import.meta.url))

const CARDS = {
	bpmn: {
		title: "BPMN agent card",
		description:
			"Cheat sheet for an AI agent building a Camunda 8 BPMN process with BPMN Kit in one command: casen build templates for one pool, pools with lanes, message flows and data, and layout-preserving edits.",
		skill: "bpmn-script",
		skillDescription:
			"Write or edit a Camunda 8 BPMN process with one `casen build` command (text spec or edit module; forms, lint and deploy included). Usage: /bpmnkit:bpmn-script <description>",
	},
	dmn: {
		title: "DMN agent card",
		description:
			"Cheat sheet for an AI agent writing a Camunda 8 DMN decision table with BPMN Kit: a runnable create/export/edit/validate script, the top builder options and the known traps.",
		skill: "dmn",
		skillDescription:
			"Write or edit a Camunda 8 DMN decision table with @bpmnkit/core (create, export, keep layout on edit, validate). Usage: /bpmnkit:dmn <description>",
	},
	form: {
		title: "Form agent card",
		description:
			"Cheat sheet for an AI agent writing a Camunda 8 form with BPMN Kit: a runnable create/export/edit/validate script, the top builder options and the known traps.",
		skill: "form",
		skillDescription:
			"Write or edit a Camunda 8 form (.form JSON) with @bpmnkit/core (create, export, keep ids on edit, validate). Usage: /bpmnkit:form <description>",
	},
}

const GENERATED = "<!-- Generated by scripts/sync-agent-cards.mjs from apps/cli/agent-cards/"

const CORE_AGENTS = `# @bpmnkit/core for agents

Do not read README.md (20 KB) or the .d.ts files. Read the one card for your task (~2k tokens each); it is self-sufficient. BPMN: write a short spec with the Write tool and run one command, \`npx casen build <spec> --deploy\` (\`@bpmnkit/cli\`); it writes the .bpmn and its forms, lints and deploys.

| You write | Read |
| --- | --- |
| BPMN process | \`node_modules/@bpmnkit/core/agent-cards/bpmn.md\` |
| DMN decision table or DRD | \`node_modules/@bpmnkit/core/agent-cards/dmn.md\` |
| Camunda form | \`node_modules/@bpmnkit/core/agent-cards/form.md\` |

Rules that hold for all three:

- New BPMN: a \`casen build\` text spec (one pool, or \`## Pool\` sections with lanes, message flows, data). DMN and forms: the builders (\`Dmn\`, \`Form\`). Never write a whole file by hand.
- Edit an existing BPMN file: an edit module, \`npx casen build edit.mjs --edit order.bpmn\` (layout kept). DMN/forms: the \`export*Preserving\` writers.
- \`formId\` and \`decisionId\` must equal the deployed form id and decision id exactly.
- One gate: \`casen build\` lints like c8ctl (bpmnlint + camunda-compat) and prints the rule's \`.bpmnlintrc\` key; a task-named command is the final word. Fix every error.
- Done = gate clean + deploy succeeds. Stop there and answer in one line: never hand-route DI or render images.
- Builder errors and check findings end with \`agent-cards/<type>.md#traps\`. Read that section.

The full API reference is \`builder-reference.md\` in this folder. Open it only when a card does not cover an option.
`

const CORE_LLMS = `# @bpmnkit/core

> BPMN 2.0, DMN and Camunda Form SDK for TypeScript. Agents: read the card for your type, not the README.

- [AGENTS.md](AGENTS.md): what to read and the rules for all types
- [BPMN card](agent-cards/bpmn.md): one \`casen build\` command; templates for one pool, pools/lanes/message flows/data, and layout-preserving edits; traps
- [DMN card](agent-cards/dmn.md): decision table and DRD script and traps
- [Form card](agent-cards/form.md): form script and traps
- [Builder reference](builder-reference.md): every builder option
`
/** @returns {Map<string, string>} path → expected content */
function expectedFiles() {
	const files = new Map()
	let order = 1
	for (const [kind, card] of Object.entries(CARDS)) {
		const source = readFileSync(join(ROOT, "apps/cli/agent-cards", `${kind}.md`), "utf8")
		const marker = `${GENERATED}${kind}.md; do not edit. -->`
		// The docs page takes its title from front matter; the body drops the H1.
		const body = source.replace(/^# .*\n+/, "")
		files.set(
			join(ROOT, "apps/landing/src/content/docs/agent-cards", `${kind}.md`),
			`---\ntitle: ${card.title}\ndescription: ${JSON.stringify(card.description)}\nsidebar:\n  order: ${order++}\n---\n\n${marker}\n\n${body}`,
		)
		files.set(
			join(ROOT, "plugins-claude/bpmnkit-claude/skills", card.skill, "SKILL.md"),
			`---\nname: ${card.skill}\ndescription: ${JSON.stringify(card.skillDescription)}\n---\n\n${marker}\n\nTask: $ARGUMENTS\n\nFollow this card. Start from its template or script, change it to fit the task, run it, and fix every lint error before you finish.\n\n${source}`,
		)
	}
	// @bpmnkit/core ships the cards so an agent with only that package installed finds them.
	const core = join(ROOT, "packages/core")
	for (const kind of Object.keys(CARDS)) {
		const source = readFileSync(join(ROOT, "apps/cli/agent-cards", `${kind}.md`), "utf8")
		files.set(join(core, "agent-cards", `${kind}.md`), source)
	}
	files.set(join(core, "AGENTS.md"), CORE_AGENTS)
	files.set(join(core, "llms.txt"), CORE_LLMS)
	return files
}

const check = process.argv.includes("--check")
const stale = []
for (const [path, content] of expectedFiles()) {
	const current = existsSync(path) ? readFileSync(path, "utf8") : undefined
	if (current === content) continue
	stale.push(relative(ROOT, path))
	if (!check) {
		mkdirSync(dirname(path), { recursive: true })
		writeFileSync(path, content)
	}
}
if (check && stale.length > 0) {
	console.error(
		`Agent card copies are stale; run node scripts/sync-agent-cards.mjs:\n  ${stale.join("\n  ")}`,
	)
	process.exit(1)
}
if (!check) console.log(stale.length ? `Updated ${stale.length} file(s)` : "Agent cards up to date")
