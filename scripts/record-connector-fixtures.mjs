// Records the expected outputs of crates/bpmnkit-connectors' parity tests from the TypeScript
// implementation (the oracle): @bpmnkit/connector-gen for OpenAPI/Swagger -> templates and
// @bpmnkit/core's applyTemplateToElement for binding templates onto BPMN elements.
//
// Needs the packages built (feel, core, connector-gen): pnpm turbo build --filter=@bpmnkit/connector-gen
// then: node scripts/record-connector-fixtures.mjs
//
// Inputs live in crates/bpmnkit-connectors/tests/fixtures/{specs,bind}; this writes
// fixtures/generate/ (cases.json + expected files), fixtures/bind/{catalog.json,cases.json,
// expected/,xml/} and src/catalog_data.rs (the generator's CATALOG), all committed.
import { createHash } from "node:crypto"
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const crate = join(root, "crates/bpmnkit-connectors")
const fixtures = join(crate, "tests/fixtures")
const load = (path) => import(pathToFileURL(join(root, path)).href)

const gen = await load("packages/connector-gen/dist/index.js")
const { applyTemplateToElement } = await load("packages/core/dist/connectors/index.js")
const { parseBpmn } = await load("packages/core/dist/bpmn/bpmn-parser.js")
const { serializeBpmn } = await load("packages/core/dist/bpmn/bpmn-serializer.js")

const read = (path) => readFileSync(path, "utf8")
const writeJson = (path, value) => writeFileSync(path, `${JSON.stringify(value, null, "\t")}\n`)
const reset = (dir) => {
	rmSync(dir, { recursive: true, force: true })
	mkdirSync(dir, { recursive: true })
}

