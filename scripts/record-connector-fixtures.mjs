// ─── Binding templates onto elements ──────────────────────────────────────────

const bindDir = join(fixtures, "bind")
const sha256 = (text) => createHash("sha256").update(text).digest("hex")
const catalog = JSON.parse(read(join(root, "crates/bpmnkit-spec/data/connectors.json")))
const baseXml = read(join(bindDir, "base.bpmn"))

function apply(xml, elementId, template, values, options) {
	const result = applyTemplateToElement(parseBpmn(xml), elementId, template, values, options)
	return { xml: serializeBpmn(result.definitions), problems: result.problems }
}
// Chains through the model like the Rust test does, so steps see each other's output.
function runSteps(xml, steps, templateOf) {
	let defs = parseBpmn(xml)
	return steps.map((step) => {
		const result = applyTemplateToElement(
			defs,
			step.element,
			templateOf(step.template),
			step.values ?? {},
			step.options ?? {},
		)
		defs = result.definitions
		return { xml: serializeBpmn(defs), problems: result.problems }
	})
}

// Every catalog template, default values, onto the base element its appliesTo names.
const elementFor = (t) =>
	({
		"bpmn:Task": "Task_1",
		"bpmn:StartEvent": "Start_1",
		"bpmn:EndEvent": "End_1",
		"bpmn:BoundaryEvent": "Boundary_1",
		"bpmn:ReceiveTask": "Receive_1",
		"bpmn:SubProcess": "Sub_1",
		"bpmn:IntermediateThrowEvent": "Throw_1",
		"bpmn:IntermediateCatchEvent": "Catch_1",
	})[t.appliesTo[0]]
const groupKey = (t) =>
	`${t.appliesTo[0]}|${t.elementType.value}|${t.elementType.eventDefinition ?? ""}`
const representative = new Set()
const seenGroups = new Set()
for (const t of catalog) {
	if (!seenGroups.has(groupKey(t))) {
		seenGroups.add(groupKey(t))
		representative.add(t.id)
	}
}
for (const id of [
	"io.camunda.connectors.HttpJson.v2",
	"camunda.connectors.rpa",
	"io.camunda.connectors.agenticai.ai-agent-subprocess.v2",
	"io.camunda.connectors.agenticai.ai-agent-task.v2",
	"io.camunda.connectors.webhook.WebhookConnector.v1",
	"io.camunda.connectors.webhook.WebhookConnectorStartMessage.v1",
	"io.camunda.connectors.http.Polling.Boundary",
	"io.camunda.connectors.inbound.KafkaReceive.v1",
]) {
	if (catalog.some((t) => t.id === id)) representative.add(id)
}
const safe = (id) => id.replace(/[^a-zA-Z0-9]/g, "-").toLowerCase()

const xmlDir = join(bindDir, "xml")
reset(xmlDir)
const catalogRecords = catalog.map((template) => {
	const element = elementFor(template)
	const { xml, problems } = apply(baseXml, element, template, {}, {})
	if (representative.has(template.id)) writeFileSync(join(xmlDir, `${safe(template.id)}.xml`), xml)
	return { id: template.id, element, sha256: sha256(xml), bytes: xml.length, problems }
})
writeJson(join(bindDir, "catalog.json"), catalogRecords)

