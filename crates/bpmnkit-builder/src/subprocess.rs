/// `makeFlowElement(id, type, options)` for the plain gateways.
pub(crate) fn plain_el(
    id: &str,
    ty: BpmnElementType,
    options: Option<&ElementOptions>,
) -> Result<BpmnFlowElement, String> {
    make_flow_element(id, ty, flow_options(options))
}

fn flow_options(options: Option<&ElementOptions>) -> FlowElementOptions {
    options.map(FlowElementOptions::from).unwrap_or_default()
}

/// Builder for the inside of a sub-process (TS's `SubProcessContentBuilder`).
#[derive(Debug)]
pub struct SubProcessContentBuilder {
    pub(crate) shared: SharedRef,
    pub(crate) scope: Scope,
    /// False inside an ad-hoc sub-process: its children are unordered, so nothing is wired.
    pub(crate) auto_connect: bool,
}

/// Runs `content` on a fresh builder sharing `shared`, then `finalize_scope` on what it
/// built (TS: `new SubProcessContentBuilder(roots, autoConnect)`, `content(sub)`,
/// `finalizeScope(sub._elements, sub._flows)`).
pub(crate) fn run_content(
    shared: &SharedRef,
    auto_connect: bool,
    content: impl FnOnce(&mut SubProcessContentBuilder),
) -> Result<ScopeContents, Failed> {
    let mut sub = SubProcessContentBuilder::new(Rc::clone(shared), auto_connect);
    content(&mut sub);
    if is_failed(shared) {
        return Err(Failed);
    }
    let Scope {
        mut elements,
        mut flows,
        text_annotations,
        associations,
        ..
    } = sub.scope;
    let finalized = finalize_scope(&mut elements, &mut flows, &mut shared.borrow_mut());
    check(shared, finalized)?;
    Ok(ScopeContents {
        elements,
        flows,
        text_annotations,
        associations,
    })
}

/// Gives a container element its content.
fn fill_contents(el: &mut BpmnFlowElement, sub: ScopeContents) {
    if let Some(c) = el.contents_mut() {
        c.flow_elements = sub.elements;
        c.sequence_flows = sub.flows;
        c.text_annotations = sub.text_annotations;
        c.associations = sub.associations;
    }
}

/// Content, then the container named `ty` with its multi-instance marker (the shared body
/// of `subProcess()` and `makeTransactionEl`).
fn make_container_el(
    shared: &SharedRef,
    id: &str,
    ty: BpmnElementType,
    content: impl FnOnce(&mut SubProcessContentBuilder),
    options: Option<&SubProcessOptions>,
) -> Result<BpmnFlowElement, Failed> {
    let sub = run_content(shared, true, content)?;
    let made = make_flow_element(id, ty, flow_options(options.map(|o| &o.element)));
    let mut el = check(shared, made)?;
    fill_contents(&mut el, sub);
    if let Some(mi) = options.and_then(|o| o.multi_instance.as_ref()) {
        if let Some(slot) = el.loop_characteristics_mut() {
            *slot = Some(build_multi_instance(mi));
        }
    }
    Ok(el)
}

