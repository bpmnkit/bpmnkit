//! Goldens (insta), determinism (I1, I3, I4, I6), stub preservation and `--check` for the Rust target.

use bpmnkit_codegen::rust::RustEmitter;
use bpmnkit_codegen::write::{check, write, Drift};
use bpmnkit_codegen::{EmitError, Emitter, GenFile, Kind};
use bpmnkit_jobspec::{analyze, schema, ApiIndex, Catalog, Inputs, WorkerConfig, WorkerProject};

const FIXTURES: [(&str, &str); 5] = [
    ("order", include_str!("fixtures/order.bpmn")),
    ("minimal", include_str!("fixtures/minimal.bpmn")),
    ("errors", include_str!("fixtures/errors.bpmn")),
    ("collisions", include_str!("fixtures/collisions.bpmn")),
    ("adhoc", include_str!("fixtures/adhoc.bpmn")),
];
const TYPED: &str = include_str!("fixtures/typed.schema.json");

fn project(xml: &str) -> WorkerProject {
    let defs = vec![bpmnkit_bpmn::parse_bpmn(xml).unwrap()];
    analyze(Inputs {
        name: "demo-workers",
        definitions: &defs,
        apis: &ApiIndex::default(),
        catalog: &Catalog::builtin(),
        config: &WorkerConfig::default(),
    })
    .project
}

fn emit(p: &WorkerProject) -> Vec<GenFile> {
    RustEmitter::default().emit(p).unwrap()
}

fn dump(files: &[GenFile]) -> String {
    let mut s = String::new();
    for f in files {
        s.push_str(&format!(
            "===== {} [{:?}] =====\n{}",
            f.path,
            f.kind,
            String::from_utf8(f.content.clone())
                .unwrap()
                .replace(env!("CARGO_PKG_VERSION"), "<version>")
        ));
    }
    s
}

#[test]
fn goldens() {
    for (name, xml) in FIXTURES {
        let files = emit(&project(xml));
        insta::assert_snapshot!(format!("golden_{name}"), dump(&files));
    }
}

#[test]
fn golden_typed_schema() {
    let mut p = project(FIXTURES[0].1);
    let s = schema::from_json(&serde_json::from_str(TYPED).unwrap()).unwrap();
    p.jobs.get_mut("charge-card").unwrap().input_schema = Some(s);
    insta::assert_snapshot!(dump(&emit(&p)));
}

#[test]
fn same_input_same_bytes() {
    for (_, xml) in FIXTURES {
        assert_eq!(emit(&project(xml)), emit(&project(xml)));
    }
}

#[test]
fn output_is_portable_and_lock_free() {
    for (_, xml) in FIXTURES {
        for f in emit(&project(xml)) {
            assert!(
                !f.path.contains('\\') && !f.path.starts_with('/'),
                "{}",
                f.path
            );
            assert_ne!(f.path, "Cargo.lock", "I6");
            let text = String::from_utf8(f.content).unwrap();
            assert!(!text.contains('\r'), "{} has CR", f.path);
            assert!(text.ends_with('\n'), "{} lacks trailing newline", f.path);
            assert!(
                !text.contains("/home/") && !text.contains("/tmp/"),
                "{}",
                f.path
            );
        }
    }
}

#[test]
fn manifest_pins_exactly_and_path_override_is_opt_in() {
    let p = project(FIXTURES[0].1);
    let manifest = |e: &RustEmitter| {
        String::from_utf8(
            e.emit(&p)
                .unwrap()
                .into_iter()
                .find(|f| f.path == "Cargo.toml")
                .unwrap()
                .content,
        )
        .unwrap()
    };
    let default = manifest(&RustEmitter::default());
    assert!(default.contains(&format!(
        "bpmnkit-worker = \"={}\"",
        env!("CARGO_PKG_VERSION")
    )));
    for line in default
        .lines()
        .filter(|l| l.contains("version = \"") || l.contains(" = \""))
    {
        assert!(!line.contains("\"^") && !line.contains("\"1\""), "{line}");
    }
    let path = manifest(&RustEmitter {
        worker_path: Some("../w".into()),
        ..Default::default()
    });
    assert!(path.contains("path = \"../w\""));
}

#[test]
fn header_carries_ir_hash_on_generated_sources() {
    let p = project(FIXTURES[0].1);
    let hash = bpmnkit_jobspec::ir_hash(&p);
    for f in emit(&p) {
        if f.kind == Kind::Generated {
            let text = String::from_utf8(f.content).unwrap();
            assert!(text.starts_with("// @generated by bpmnkit "), "{}", f.path);
            assert!(text
                .lines()
                .next()
                .unwrap()
                .contains(&format!("sha256:{hash} — DO NOT EDIT")));
        }
    }
}

#[test]
fn colliding_names_get_suffixes() {
    let files = emit(&project(FIXTURES[3].1));
    let paths: Vec<_> = files.iter().map(|f| f.path.as_str()).collect();
    assert!(
        paths.contains(&"src/gen/ship_order.rs") && paths.contains(&"src/gen/ship_order2.rs"),
        "{paths:?}"
    );
    assert!(
        paths.contains(&"src/gen/fn_.rs"),
        "keyword module: {paths:?}"
    );
}

#[test]
fn only_worker_jobs_unless_all() {
    let mut p = project(FIXTURES[0].1);
    for job in p.jobs.values_mut() {
        job.classified.as_mut().unwrap().decision = bpmnkit_jobspec::Decision::Rest;
    }
    assert_eq!(RustEmitter::default().emit(&p), Err(EmitError::NoJobs));
    assert!(RustEmitter {
        all: true,
        ..Default::default()
    }
    .emit(&p)
    .is_ok());
}

#[test]
fn regeneration_keeps_stubs_and_restores_generated() {
    let dir = tempfile::tempdir().unwrap();
    let files = emit(&project(FIXTURES[0].1));
    write(dir.path(), &files).unwrap();
    assert!(check(dir.path(), &files).is_empty());

    let handler = dir.path().join("src/handlers/charge_card.rs");
    let generated = dir.path().join("src/gen/errors.rs");
    std::fs::write(&handler, "// mine\n").unwrap();
    std::fs::write(&generated, "// edited\n").unwrap();
    std::fs::remove_file(dir.path().join("README.md")).unwrap();
    let drift = check(dir.path(), &files);
    assert_eq!(drift.len(), 2, "{drift:?}");
    assert!(drift.contains(&Drift::Missing("README.md".into())));

    let second = write(dir.path(), &files).unwrap();
    assert_eq!(std::fs::read_to_string(&handler).unwrap(), "// mine\n");
    assert!(std::fs::read_to_string(&generated)
        .unwrap()
        .contains("DO NOT EDIT"));
    assert_eq!(second.updated.len(), 1);
    assert!(second.kept.contains(&"Cargo.toml".to_owned()));
    assert!(check(dir.path(), &files).is_empty());
}

#[test]
fn lock_file_lists_rules_and_hash() {
    let p = project(FIXTURES[0].1);
    let lock = bpmnkit_codegen::lock::lock_file(&p, "rust");
    let text = String::from_utf8(lock.content.clone()).unwrap();
    assert!(text.contains(&format!("\"irHash\": \"{}\"", bpmnkit_jobspec::ir_hash(&p))));
    assert!(text.contains("\"charge-card\"") && text.contains("\"rule\""));
    assert_eq!(lock, bpmnkit_codegen::lock::lock_file(&p, "rust"));
    assert_eq!(lock.kind, Kind::Generated);
}
