//! Deterministic job worker code generation (plan `doc/plans/c8-workers-and-rust-cli.md`, P4).
//!
//! Every target implements [`Emitter`]: IR in, a sorted list of [`GenFile`]s out. Writing and
//! `--check` live in [`write`] and are shared by all targets (the Rust emitter of P3 plugs in
//! the same way). Invariants I1–I4 and I6 hold by construction: no clock, no environment, no
//! absolute paths, `BTreeMap` only, `/` separators, LF only (except the embedded `mvnw.cmd`).

use bpmnkit_jobspec::{Decision, JobSpec, WorkerProject};

pub mod java;
mod names;
pub mod write;

pub use names::{lower_camel, pascal, upper_snake};

/// How a generated file is treated on (re)generation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// Owned by the generator: always overwritten, carries the `DO NOT EDIT` header.
    Generated,
    /// Written once, then owned by the user: never overwritten.
    Once,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenFile {
    /// Relative, `/`-separated.
    pub path: String,
    pub content: Vec<u8>,
    pub kind: Kind,
    /// Unix executable bit (`mvnw`).
    pub executable: bool,
}

impl GenFile {
    pub fn generated(path: impl Into<String>, content: impl Into<Vec<u8>>) -> Self {
        Self::new(path, content, Kind::Generated)
    }

    pub fn once(path: impl Into<String>, content: impl Into<Vec<u8>>) -> Self {
        Self::new(path, content, Kind::Once)
    }

    fn new(path: impl Into<String>, content: impl Into<Vec<u8>>, kind: Kind) -> Self {
        Self {
            path: path.into(),
            content: content.into(),
            kind,
            executable: false,
        }
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum EmitError {
    /// No job to generate for: nothing classified as worker (and `all` unset).
    NoJobs,
    /// Two files ended up at the same path.
    DuplicatePath(String),
}

impl std::fmt::Display for EmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            EmitError::NoJobs => f.write_str(
                "no job type is classified as worker (use --all to generate for every job type)",
            ),
            EmitError::DuplicatePath(p) => write!(f, "two generated files share the path {p}"),
        }
    }
}

impl std::error::Error for EmitError {}

/// A code generation target.
pub trait Emitter {
    /// `java`, `rust`, …
    fn target(&self) -> &'static str;
    /// Files for the project, sorted by path. Deterministic: same IR and options, same bytes.
    fn emit(&self, project: &WorkerProject) -> Result<Vec<GenFile>, EmitError>;
}

/// The jobs a worker is generated for: those the rules classified as worker, or all with `all`.
pub fn select_jobs(project: &WorkerProject, all: bool) -> Vec<&JobSpec> {
    project
        .jobs
        .values()
        .filter(|j| {
            all || matches!(
                j.classified.as_ref().map(|c| &c.decision),
                Some(Decision::Worker)
            )
        })
        .collect()
}

/// Sort by path and reject duplicates; the single exit of every emitter.
pub fn finish(mut files: Vec<GenFile>) -> Result<Vec<GenFile>, EmitError> {
    files.sort_by(|a, b| a.path.cmp(&b.path));
    if let Some(w) = files.windows(2).find(|w| w[0].path == w[1].path) {
        return Err(EmitError::DuplicatePath(w[0].path.clone()));
    }
    Ok(files)
}

/// The header of every generated source file (plan I4). `comment` is the line-comment leader.
pub fn header(comment: &str, ir_hash: &str) -> String {
    format!(
        "{comment} @generated by bpmnkit {} — sha256:{ir_hash} — DO NOT EDIT\n",
        env!("CARGO_PKG_VERSION")
    )
}
