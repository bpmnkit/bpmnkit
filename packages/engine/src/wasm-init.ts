/**
 * Shared reebe-wasm loader. Not a public export: the scenario runner and the
 * CPT runner both need the engine initialised exactly once per process.
 */

let wasmReady = false

export async function ensureWasmInit(): Promise<void> {
	if (wasmReady) return
	let mod: typeof import("@bpmnkit/reebe-wasm")
	try {
		mod = await import("@bpmnkit/reebe-wasm")
	} catch (e) {
		throw new Error(
			`@bpmnkit/reebe-wasm is not installed. Run: npm install @bpmnkit/reebe-wasm\nCaused by: ${e instanceof Error ? e.message : String(e)}`,
		)
	}
	// Node.js: fetch() does not support file:// URLs generated by wasm-bindgen,
	// so we read the .wasm bytes from disk and use initSync.
	if (typeof process !== "undefined" && typeof process.versions?.node === "string") {
		const { readFileSync } = await import("node:fs")
		const { createRequire } = await import("node:module")
		const { dirname, resolve } = await import("node:path")
		const req = createRequire(import.meta.url)
		const jsPath: string = req.resolve("@bpmnkit/reebe-wasm")
		const wasmPath = resolve(dirname(jsPath), "reebe_wasm_bg.wasm")
		mod.initSync({ module: readFileSync(wasmPath) })
	} else {
		await mod.default()
	}
	wasmReady = true
}
